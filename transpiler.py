"""Transpile the supported ASAAN subset into readable Python."""
from pathlib import Path
import re

def transpile(source: str) -> str:
    output = ["# Generated by ASAANIDE. Review before running.", ""]
    for number, raw in enumerate(source.splitlines(), 1):
        if not raw.strip() or raw.lstrip().startswith("#"):
            output.append(raw); continue
        indent = len(raw) - len(raw.lstrip(" "))
        s = raw.strip()
        m = re.match(r"var\.([A-Za-z_]\w*)/\w+\s*=\s*(.+)", s)
        if m:
            output.append(" " * indent + f"{m.group(1)} = {m.group(2)}")
        elif s.startswith("print:"):
            output.append(" " * indent + f"print({s[6:].strip()})")
        elif s.startswith("calc.calculate |"):
            output.append(" " * indent + "calculate = " + s.split("|",1)[1].strip())
        elif s.startswith("if ") or s.startswith("elif ") or s == "else:":
            output.append(" " * indent + s)
        elif s.startswith("for ") and s.endswith(":"):
            fm = re.match(r"for\s+var\.([A-Za-z_]\w*)/\w+\s+in\s+(-?\d+)\.\.(-?\d+):", s)
            if not fm: raise ValueError(f"Line {number}: unsupported for loop")
            name, a, b = fm.groups()
            output.append(" " * indent + f"for {name} in range({a}, {int(b)+1}):")
        else:
            raise ValueError(f"Line {number}: cannot transpile '{s}'")
    return "\n".join(output) + "\n"

def compile_file(path):
    return transpile(Path(path).read_text(encoding="utf-8"))
